function toAzDisplayAmount(displayAmountEn: string): string {
  return displayAmountEn
    .replace(/\bto taste\b/gi, 'zövqə görə')
    .replace(/\bcloves\b/gi, 'diş')
    .replace(/\bclove\b/gi, 'diş')
    .replace(/\btbsp\b/gi, 'x.q.')
    .replace(/\btsp\b/gi, 'ç.q.')
    .replace(/\bpcs\b/gi, 'ədəd');
}

function ing(
  id: string,
  canonicalIngredient: string,
  namePl: string,
  nameEn: string,
  amount: number,
  unit: RecipeIngredient['unit'],
  displayAmountPl: string,
  displayAmountEn: string,
  category: RecipeIngredient['category'],
  icon: string,
  nameAzOverride?: string
): RecipeIngredient {
  const norm = normalizeIngredientQuantity(amount, unit, canonicalIngredient);
  return {
    id,
    canonicalIngredient,
    namePl,
    nameEn,
    nameAz: nameAzOverride || CANONICAL_AZ_NAMES[canonicalIngredient] || nameEn,
    amount,
    unit,
    displayAmountPl,
    displayAmountEn,
    displayAmountAz: toAzDisplayAmount(displayAmountEn),
    normalizedBaseAmount: norm.amount,
    normalizedBaseUnit: norm.baseUnit,
    category,
    icon,
  };
}

